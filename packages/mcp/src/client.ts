import { createClient } from '@interlock/client';
import { readApiToken } from '@interlock/core/apiToken';

// Match the server caller so both transports use the same tool registrations.
export function createMcpClient(url?: string) {
  // The stdio bridge sends the token from disk, so its configuration needs no secret.
  const client = createClient(url, { token: readApiToken() });
  return {
    report: { summary: client.report.summary.query },
    system: {
      doctor: client.system.doctor.query,
      report: client.system.report.query,
    },
    stalls: { manage: client.stalls.manage.mutate },
    triggers: {
      read: client.triggers.read.query,
      manage: client.triggers.manage.mutate,
    },
    pauses: {
      list: client.pauses.list.query,
      pause: client.pauses.pause.mutate,
      resume: client.pauses.resume.mutate,
    },
    variables: {
      read: client.variables.read.query,
      manage: client.variables.manage.mutate,
    },
    modelAliases: {
      read: client.modelAliases.read.query,
      mutate: client.modelAliases.mutate.mutate,
    },
    executors: { manage: client.executors.manage.mutate },
    boards: {
      list: client.boards.list.query,
      get: client.boards.get.query,
      settings: client.boards.settings.query,
      save: client.boards.save.mutate,
      assign: client.boards.assign.mutate,
    },
    requests: {
      list: client.requests.list.query,
      get: client.requests.get.query,
      answer: client.requests.answer.mutate,
    },
    testbench: {
      simulation: client.testbench.simulation.mutate,
      suites: client.testbench.suites.query,
      suite: client.testbench.suite.query,
      createSuite: client.testbench.createSuite.mutate,
      updateSuite: client.testbench.updateSuite.mutate,
      preview: client.testbench.preview.query,
      start: client.testbench.start.mutate,
      comparisons: client.testbench.comparisons.query,
      report: client.testbench.report.query,
      case: client.testbench.case.query,
      trial: client.testbench.trial.query,
      cleanupTrial: client.testbench.cleanupTrial.mutate,
      cancel: client.testbench.cancel.mutate,
      judge: client.testbench.judge.mutate,
    },
    prompts: {
      list: client.prompts.list.query,
      get: client.prompts.get.query,
      create: client.prompts.create.mutate,
      update: client.prompts.update.mutate,
      delete: client.prompts.delete.mutate,
    },
    workflows: {
      starters: client.workflows.starters.query,
      importStarter: client.workflows.importStarter.mutate,
      previewOwnership: client.workflows.previewOwnership.query,
      setOwner: client.workflows.setOwner.mutate,
      versions: client.workflows.versions.query,
      previewVersionDeletion: client.workflows.previewVersionDeletion.query,
      deleteVersions: client.workflows.deleteVersions.mutate,
      delete: client.workflows.delete.mutate,
      export: client.workflows.export.query,
      import: client.workflows.import.mutate,
      list: client.workflows.list.query,
      get: client.workflows.get.query,
      create: client.workflows.create.mutate,
      createSummary: client.workflows.createSummary.mutate,
      updateSummary: client.workflows.updateSummary.mutate,
      publishSummary: client.workflows.publishSummary.mutate,
      update: client.workflows.update.mutate,
      edit: client.workflows.edit.mutate,
      validate: client.workflows.validate.query,
      publish: client.workflows.publish.mutate,
    },
    runs: {
      versionPolicy: client.runs.versionPolicy.query,
      setVersionPolicy: client.runs.setVersionPolicy.mutate,
      previewVersionMove: client.runs.previewVersionMove.query,
      applyVersionMove: client.runs.applyVersionMove.mutate,
      script: client.runs.script.mutate,
      externalInputStatus: client.runs.externalInputStatus.query,
      externalInput: client.runs.externalInput.mutate,
      retentionSettings: client.runs.retentionSettings.query,
      configureRetention: client.runs.configureRetention.mutate,
      retentionStatus: client.runs.retentionStatus.query,
      previewHistoryDeletion: client.runs.previewHistoryDeletion.query,
      deleteHistory: client.runs.deleteHistory.mutate,
      budget: client.runs.budget.query,
      contextGroup: client.runs.contextGroup.query,
      handoffContext: client.runs.handoffContext.mutate,
      setBudget: client.runs.setBudget.mutate,
      usage: client.runs.usage.query,
      startSummary: client.runs.startSummary.mutate,
      briefing: client.runs.briefing.query,
      wait: client.runs.wait.query,
      result: client.runs.result.query,
      find: client.runs.find.query,
      start: client.runs.start.mutate,
      get: client.runs.get.query,
      retry: client.runs.retry.mutate,
      previewCancellation: client.runs.previewCancellation.query,
      cancelTree: client.runs.cancelTree.mutate,
      cancel: client.runs.cancel.mutate,
    },
    work: {
      hold: client.work.hold.mutate,
      resources: client.work.resources.mutate,
      preflight: client.work.preflight.query,
      size: client.work.size.query,
      reportUsage: client.work.reportUsage.mutate,
      submitSummary: client.work.submitSummary.mutate,
      summaries: client.work.summaries.query,
      list: client.work.list.query,
      claim: client.work.claim.mutate,
      submit: client.work.submit.mutate,
      renew: client.work.renew.mutate,
      fail: client.work.fail.mutate,
    },
  };
}
